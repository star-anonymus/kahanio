// Ports ClientoraHQ's own cartoon characters (Clientora_Studio/brand/mascot/*.html) into src/characters.generated.ts.
// Each becomes: the SVG markup plus a pose function that works on a detached SVG (ids looked up inside it).
// Run: node scripts/port-characters.mjs  (re-run after a character changes in the Studio repo)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = join(import.meta.dirname, "..", "..", "Clientora_Studio", "brand", "mascot");
const LIST = [
  { id: "bilal", name: "Bilal", role: "Web designer" },
  { id: "baji", name: "Baji", role: "Home baker" },
  { id: "ustad", name: "Ustad", role: "Chai wala" },
  { id: "chacha", name: "Chacha", role: "Shopkeeper" },
];

let out = `// GENERATED by scripts/port-characters.mjs from Clientora_Studio/brand/mascot. Do not edit by hand.\n// Characters are ClientoraHQ's own artwork.\n// @ts-nocheck\n\nexport const CHARACTER_LIST = ${JSON.stringify(LIST.map(({ id, name, role }) => ({ id, name, role })))} as const;\n\n`;
const svgs = [];
const posers = [];
for (const c of LIST) {
  const html = readFileSync(join(SRC, `${c.id}.html`), "utf8");
  const svg = html.slice(html.indexOf("<svg"), html.indexOf("</svg>") + 6);
  const start = html.indexOf("window.pose = ");
  const end = html.indexOf("\n  pose();", start);
  if (!svg.startsWith("<svg") || start < 0 || end < 0) throw new Error(`could not read ${c.id}`);
  const fn = html.slice(start + "window.pose = ".length, end).trim().replace(/;$/, "");
  svgs.push(`  ${c.id}: ${JSON.stringify(svg)}`);
  posers.push(`  ${c.id}: ($) => ${fn}`);
}
out += `export const CHARACTER_SVGS = {\n${svgs.join(",\n")},\n};\n\nexport const CHARACTER_POSERS = {\n${posers.join(",\n")},\n};\n`;
writeFileSync(join(import.meta.dirname, "..", "src", "characters.generated.ts"), out);
console.log("wrote", LIST.map((c) => c.id).join(", "));
